#!/usr/bin/env node
// Builds the Nore design tokens from design/tokens.json into:
//   design/tokens.css                                          (website, launcher, updater, mocks)
//   common/src/main/java/dev/noreclient/util/ThemeTokens.java   (in-game client)
// Usage: node design/build-tokens.mjs [--check]
// --check exits 1 when the outputs on disk differ from what the JSON produces.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const T = JSON.parse(readFileSync(join(HERE, 'tokens.json'), 'utf8'));
const CSS_OUT = join(HERE, 'tokens.css');
const JAVA_OUT = join(ROOT, 'common/src/main/java/dev/noreclient/util/ThemeTokens.java');

// ---------------------------------------------------------------- helpers
const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const CONST = s => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[-.]/g, '_').toUpperCase();
const bez = a => `cubic-bezier(${a.join(', ')})`;
const val = t => (typeof t === 'object' && t !== null && 'value' in t ? t.value : t);
const hexOf = t => {
  const v = typeof t === 'object' ? (t.fallback ?? t.value) : t;
  return typeof v === 'string' && /^#|^rgba?\(/.test(v) ? v : null;
};

// Damped spring step response sampled into a CSS linear() easing.
function springCurve({ stiffness: k, damping: c, mass: m = 1 }) {
  const dt = 1 / 600; let x = 0, v = 0, t = 0; const pts = [];
  let settled = 0;
  while (t < 3) {
    const a = (-k * (x - 1) - c * v) / m; v += a * dt; x += v * dt; t += dt;
    pts.push([t, x]);
    if (Math.abs(x - 1) < 0.002 && Math.abs(v) < 0.02) { if (!settled) settled = t; if (t - settled > 0.03) break; } else settled = 0;
  }
  const dur = pts[pts.length - 1][0];
  const N = 28; const out = [];
  for (let i = 0; i <= N; i++) {
    const tt = (i / N) * dur;
    const p = pts.reduce((b, q) => (Math.abs(q[0] - tt) < Math.abs(b[0] - tt) ? q : b));
    out.push(i === 0 ? '0' : i === N ? '1' : `${p[1].toFixed(3)} ${((i / N) * 100).toFixed(1)}%`);
  }
  return { css: `linear(${out.join(', ')})`, ms: Math.round(dur * 1000) };
}

function argb(css, alphaOverride) {
  if (!css) return null;
  let m;
  if ((m = css.match(/^#([0-9a-f]{8})$/i))) return '0x' + m[1].toUpperCase();
  if ((m = css.match(/^#([0-9a-f]{6})$/i))) return '0x' + (alphaOverride ?? 'FF') + m[1].toUpperCase();
  if ((m = css.match(/^rgba?\(([^)]+)\)$/))) {
    const [r, g, b, a = 1] = m[1].split(',').map(s => parseFloat(s));
    const h = n => Math.round(n).toString(16).padStart(2, '0').toUpperCase();
    return '0x' + h(a * 255) + h(r) + h(g) + h(b);
  }
  return null;
}

function lum(hex) {
  const m = hex.match(/^#([0-9a-f]{6})$/i); if (!m) return null;
  const c = [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16) / 255).map(u => (u <= 0.03928 ? u / 12.92 : ((u + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
const contrast = (a, b) => { const x = lum(a), y = lum(b); return ((Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)).toFixed(2); };

// ---------------------------------------------------------------- CSS
function buildCss() {
  const L = [];
  const c = T.color;
  L.push('/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit. */');
  L.push('/* Fonts: Dela Gothic One, Onest, Pixelify Sans (all SIL OFL 1.1). The website may load them from');
  L.push('   Google Fonts; the launcher and updater must self-host the woff2 files (CSP font-src \'self\'). */');
  L.push(':root {');
  L.push('  color-scheme: dark;');
  L.push(`  --nore-accent: ${c.accent.accent.value};`);
  for (const [k, t] of Object.entries(c.accent)) if (k !== 'accent') L.push(`  --nore-${k}: ${val(t)};`);
  for (const [k, t] of Object.entries(c.base)) L.push(`  --nore-${k}: ${val(t)};`);
  for (const [k, t] of Object.entries(c.dot)) L.push(`  --nore-dot-${k}: ${val(t)};`);
  for (const [k, t] of Object.entries(c.label)) L.push(`  --nore-label-${k}: ${val(t)};`);
  for (const [k, t] of Object.entries(c.tape)) L.push(`  --nore-tape-${k}: ${val(t)};`);
  L.push(`  --nore-foil: conic-gradient(from var(--nore-foil-angle, 0deg), ${c.foil.stops.value.join(', ')});`);
  // event-only colours are available everywhere (for previews) but only switched on by data-event
  for (const ev of ['halloween', 'winter']) for (const [k, t] of Object.entries(c.event[ev])) if (!['page', 'page-raised', 'slot', 'cover', 'ink', 'ink-soft'].includes(k)) L.push(`  --nore-${ev}-${k}: ${val(t)};`);
  L.push('');
  const f = T.font;
  for (const [k, t] of Object.entries(f)) if (t.stack) L.push(`  --nore-font-${k}: ${t.stack};`);
  L.push('');
  for (const [surface, steps] of Object.entries(T.type)) {
    if (surface === 'game') continue;
    for (const [k, s] of Object.entries(steps)) {
      const size = typeof s.size === 'number' ? `${s.size}px` : s.size;
      const line = typeof s.line === 'number' && s.line > 3 ? `${s.line}px` : s.line;
      L.push(`  --nore-${surface}-${k}: ${s.weight ?? 400} ${size}/${line} var(--nore-font-${s.font});`);
      if (s.tracking) L.push(`  --nore-${surface}-${k}-tracking: ${s.tracking};`);
    }
  }
  L.push('');
  for (const [k, v] of Object.entries(T.space.scale)) L.push(`  --nore-space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.space.launcher)) L.push(`  --nore-launcher-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.space.web)) L.push(`  --nore-web-${k}: ${v};`);
  for (const [k, v] of Object.entries(T.radius)) if (typeof v === 'number') L.push(`  --nore-radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.rim)) if (typeof v === 'number' && k !== 'game') L.push(`  --nore-rim-${k}: ${v}px;`);
  for (const [k, t] of Object.entries(T.elevation)) L.push(`  --nore-shadow-${k}: ${t.value};`);
  L.push('');
  const m = T.motion;
  for (const [k, t] of Object.entries(m.duration)) L.push(`  --nore-dur-${k}: ${t.value}ms;`);
  for (const [k, t] of Object.entries(m.easing)) L.push(`  --nore-ease-${k}: ${bez(t.value)};`);
  for (const [k, s] of Object.entries(m.spring)) { const sc = springCurve(s); L.push(`  --nore-spring-${k}: ${sc.css};`); L.push(`  --nore-spring-${k}-dur: ${sc.ms}ms;`); }
  L.push(`  --nore-stagger: ${m.stagger.step}ms;`);
  L.push(`  --nore-stagger-max: ${m.stagger.max};`);
  for (const [k, t] of Object.entries(m.distance)) L.push(`  --nore-${kebab(k).startsWith('stick') ? kebab(k) : 'shift-' + kebab(k)}: ${t.value}${/scale/i.test(k) ? '' : /tilt/i.test(k) ? 'deg' : 'px'};`);
  L.push('}');
  L.push('');
  // events
  for (const ev of ['halloween', 'winter']) {
    L.push(`[data-event="${ev}"] {`);
    for (const k of ['page', 'page-raised', 'slot', 'cover', 'ink', 'ink-soft']) if (c.event[ev][k]) L.push(`  --nore-${k}: ${val(c.event[ev][k])};`);
    L.push('}');
  }
  L.push('');
  L.push('@media (prefers-reduced-motion: reduce) {');
  L.push('  :root {');
  for (const k of Object.keys(m.distance)) if (!/scale/i.test(k)) L.push(`    --nore-${kebab(k).startsWith('stick') ? kebab(k) : 'shift-' + kebab(k)}: 0${/tilt/i.test(k) ? 'deg' : 'px'};`);
  L.push('    --nore-stick-scale: 1;');
  for (const k of Object.keys(m.spring)) { L.push(`    --nore-spring-${k}: ${bez(m.easing.out.value)};`); L.push(`    --nore-spring-${k}-dur: ${m.duration.quick.value}ms;`); }
  for (const k of ['page', 'overlay', 'stick', 'peel', 'launch', 'reveal']) L.push(`    --nore-dur-${k}: ${Math.min(m.duration[k].value, m.reduced['duration-cap'])}ms;`);
  L.push('  }');
  L.push('}');
  L.push('/* The in-app animation switch: same as reduced motion. */');
  L.push('.no-anim, .no-anim * { transition-duration: 0ms !important; animation-duration: 0ms !important; animation-iteration-count: 1 !important; }');
  return L.join('\n') + '\n';
}

// ---------------------------------------------------------------- Java
function buildJava() {
  const c = T.color; const L = [];
  const col = (name, css, doc) => { const a = argb(css); if (a) L.push(`    /** ${doc || css} */\n    public static final int ${CONST(name)} = ${a};`); };
  L.push('package dev.noreclient.util;');
  L.push('');
  L.push('/**');
  L.push(' * Nore "Album" design tokens for the in-game client. Generated by design/build-tokens.mjs from');
  L.push(' * design/tokens.json; do not edit by hand. Colours are packed ARGB, sizes are GUI pixels,');
  L.push(' * durations milliseconds. The accent stays user-themable through {@link Theme#accent()}.');
  L.push(' */');
  L.push('public final class ThemeTokens {');
  L.push('    private ThemeTokens() {}');
  L.push('');
  L.push('    // ---- surfaces (in-game alphas: the world shows through a little)');
  for (const [k, v] of Object.entries(T.game.color)) col(k, v, `${k} (${v})`);
  L.push('');
  L.push('    // ---- accent (default; runtime accent comes from Theme.accent())');
  for (const [k, t] of Object.entries(c.accent)) col(k, hexOf(t), t.role.split('.')[0]);
  L.push('');
  L.push('    // ---- dot stickers (state)');
  for (const [k, t] of Object.entries(c.dot)) col('dot-' + k, hexOf(t), t.role.split('.')[0]);
  L.push('');
  L.push('    // ---- label stickers (loaders, versions)');
  for (const [k, t] of Object.entries(c.label)) col('label-' + k, hexOf(t), t.role.split('.')[0]);
  L.push('');
  L.push('    // ---- washi tape');
  for (const [k, t] of Object.entries(c.tape)) col('tape-' + k, hexOf(t), t.role.split('.')[0]);
  L.push('');
  L.push('    // ---- foil stops (rare / event stickers)');
  L.push(`    public static final int[] FOIL = { ${c.foil.stops.value.map(h => argb(h)).join(', ')} };`);
  for (const ev of ['halloween', 'winter']) {
    L.push('');
    L.push(`    // ---- event: ${ev}`);
    for (const [k, t] of Object.entries(c.event[ev])) col(ev + '-' + k, hexOf(t), (t.role || k).split('.')[0]);
  }
  L.push('');
  L.push('    // ---- geometry (GUI px)');
  for (const [k, v] of Object.entries(T.radius.game)) L.push(`    public static final float RADIUS_${CONST(k)} = ${v}f;`);
  L.push(`    public static final float RIM = ${T.rim.game}f;`);
  for (const [k, v] of Object.entries(T.space.game)) L.push(`    public static final int SPACE_${CONST(k)} = ${v};`);
  L.push(`    /** GUI scale the mocks are drawn for; layouts must still work at 2 and 4. */`);
  L.push(`    public static final int REFERENCE_GUI_SCALE = ${T.game.guiScale};`);
  L.push('');
  L.push('    // ---- motion (ms)');
  for (const [k, t] of Object.entries(T.motion.duration)) L.push(`    public static final int DUR_${CONST(k)} = ${t.value};`);
  L.push(`    public static final int STAGGER_STEP = ${T.motion.stagger.step};`);
  L.push(`    public static final int STAGGER_MAX = ${T.motion.stagger.max};`);
  L.push('');
  L.push('    /** Cubic-bezier control points {x1, y1, x2, y2}. */');
  for (const [k, t] of Object.entries(T.motion.easing)) L.push(`    public static final float[] EASE_${CONST(k)} = { ${t.value.map(n => n + 'f').join(', ')} };`);
  L.push('');
  L.push('    /** Spring constants {stiffness, damping, mass}; integrate per frame with dt capped at 0.05s. */');
  for (const [k, s] of Object.entries(T.motion.spring)) L.push(`    public static final float[] SPRING_${CONST(k)} = { ${s.stiffness}f, ${s.damping}f, ${s.mass}f };`);
  L.push('');
  L.push(`    public static final float STICK_SCALE = ${T.motion.distance.stickScale.value}f;`);
  L.push(`    public static final float LIFT_PX = 1f; // GUI px; the launcher lifts 3 device px, in game 1 GUI px = 3 device px at scale 3`);
  L.push('}');
  return L.join('\n') + '\n';
}

const css = buildCss();
const java = buildJava();
const check = process.argv.includes('--check');
if (check) {
  const bad = [[CSS_OUT, css], [JAVA_OUT, java]].filter(([p, s]) => !existsSync(p) || readFileSync(p, 'utf8') !== s);
  if (bad.length) { console.error('Out of date: ' + bad.map(b => b[0]).join(', ')); process.exit(1); }
  console.log('tokens up to date');
} else {
  writeFileSync(CSS_OUT, css);
  writeFileSync(JAVA_OUT, java);
  console.log('wrote', CSS_OUT);
  console.log('wrote', JAVA_OUT);
  const b = T.color.base, a = T.color.accent;
  const rows = [
    ['ink on page', b.ink.value, b.page.value], ['ink-soft on page', b['ink-soft'].value, b.page.value], ['ink-faint on page', b['ink-faint'].value, b.page.value],
    ['ink-soft on page-raised', b['ink-soft'].value, b['page-raised'].value], ['vinyl-ink on vinyl', b['vinyl-ink'].value, b.vinyl.value], ['vinyl-ink-soft on paper', b['vinyl-ink-soft'].value, b.paper.value],
    ['white on accent', a['accent-ink'].value, a.accent.value], ['white on accent-deep', a['accent-ink'].value, a['accent-deep'].value], ['accent-light on page', a['accent-light'].value, b.page.value],
    ['cover-ink-soft on cover', b['cover-ink-soft'].value, b.cover.fallback], ['page on accent', b.page.value, a.accent.value],
  ];
  for (const [n, x, y] of rows) console.log(`  contrast ${n.padEnd(26)} ${contrast(x, y)}:1`);
}
